// Regenerates lib/season.js (upgrade tracks, crest costs, catalyst items) from
// Raidbots' public game data. Run when a new season starts.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://www.raidbots.com/static/data/live';

const get = async (name) => {
  const res = await fetch(`${BASE}/${name}.json`);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  return res.json();
};

const [bonuses, conversions, sets] = await Promise.all([get('bonuses'), get('item-conversions'), get('item-sets')]);

const ups = Object.values(bonuses).filter((b) => b.upgrade?.seasonId);
const season = Math.max(...ups.map((b) => b.upgrade.seasonId));

const tracks = {};
const upgrades = {};
const currencies = {};
for (const b of ups.filter((x) => x.upgrade.seasonId === season)) {
  const u = b.upgrade;
  const cost = u.costs?.[0]?.amounts?.[0];
  if (cost) currencies[cost.currencyId] = cost.name;
  tracks[u.group] ??= { name: u.name, max: u.max, levels: {} };
  tracks[u.group].levels[u.level] = { bonus: b.id, ilvl: u.itemLevel, cost: cost ? [cost.currencyId, cost.amount] : null };
  upgrades[b.id] = [u.group, u.level];
}

const conv = Object.values(conversions).sort((a, b) => b.id - a.id)[0];
const setSlots = {};
for (const s of Object.values(sets)) for (const id of s.items ?? []) setSlots[id] = s.id;
const INV_SLOT = { 1: 'head', 3: 'shoulder', 5: 'chest', 20: 'chest', 6: 'waist', 7: 'legs', 8: 'feet', 9: 'wrist', 10: 'hands', 16: 'back' };
const catalyst = {};
for (const item of conv.items) {
  const slot = INV_SLOT[item.inventoryType];
  if (!slot) continue;
  for (const cls of item.allowableClasses ?? []) {
    (catalyst[cls] ??= {})[slot] = {
      id: item.id,
      name: item.name,
      bonus: item.bonusLists ?? [],
      set: setSlots[item.id] ?? null,
    };
  }
}

const data = {
  season,
  currencies,
  tracks,
  upgrades,
  catalyst: { bonus: conv.bonusIds, redirect: conv.shouldRedirectStats, items: catalyst },
};

fs.writeFileSync(path.join(ROOT, 'lib', 'season.js'),
  `// Generated by scripts/update-season-data.mjs from Raidbots' public data. Don't edit.\n\n`
  + `export default ${JSON.stringify(data)};\n`);
console.log(`Season ${season}: ${Object.keys(tracks).length} tracks, ${Object.keys(catalyst).length} classes.`);
