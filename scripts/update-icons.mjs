// Regenerates lib/icons.js (item icons and quality, gem icons, enchant names) for
// the current expansion from Raidbots' public game data. Run with update-season-data.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://www.raidbots.com/static/data/live';

const get = async (name) => {
  const res = await fetch(`${BASE}/${name}.json`);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  return res.json();
};

const [items, enchants] = await Promise.all([get('equippable-items'), get('enchantments')]);
const expansion = Math.max(...items.map((i) => i.expansion ?? 0));

// id -> [icon, quality]
const itemIcons = {};
for (const i of items) if (i.expansion === expansion && i.icon) itemIcons[i.id] = [i.icon, i.quality ?? 4];

// Gems by item id; enchants by enchant id, named after the item that applies them.
const gems = {};
const enchantNames = {};
for (const e of enchants) {
  if (e.expansion !== expansion) continue;
  if (e.slot === 'socket' && e.itemId && e.itemIcon) gems[e.itemId] = [e.itemIcon, e.itemName];
  else if (e.itemName) enchantNames[e.id] = [e.itemIcon || e.spellIcon || '', e.itemName];
}

const out = `// Generated by scripts/update-icons.mjs from Raidbots' public data. Don't edit.\n\nexport default ${JSON.stringify({ expansion, items: itemIcons, gems, enchants: enchantNames })};\n`;
fs.writeFileSync(path.join(ROOT, 'lib', 'icons.js'), out);
console.log(`lib/icons.js: ${Object.keys(itemIcons).length} items, ${Object.keys(gems).length} gems, ${Object.keys(enchantNames).length} enchants (expansion ${expansion}), ${Math.round(out.length / 1024)} KB`);
